"""Panel inventory (ROUND19 R19-T): which panel enters which analysis, read from the result directories; K, items and rating columns from data_panels.
Writes results/panel_inventory.md. Usage: python panel_inventory.py"""
import os, sys, glob, re
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import data_panels
R = f"{HERE}/results"
def names(pattern, strip):
    return {re.sub(strip, "", os.path.basename(p)) for p in glob.glob(f"{R}/{pattern}")}
COLS = {
    "split-half reliability": names("rho_exact/*.json", r"\.json$") | names("finite_rater/*_loo.json", r"_loo\.json$"),
    "X_own (R19-1)": names("rho_own/*.json", r"\.json$"),
    "decoding (Table 2)": names("decoding_v2/*_d64_E_last.json", r"_d64_E_last\.json$"),
    "annotation shrinkage": names("shrinkage/*_bfix.json", r"_a\d+_bfix\.json$"),
    "target heads": {p for p in names("probe_shrink/*", r"$") if not p.endswith(("_olmo", "_qwen3"))},
    "budget heads": {p for p in names("budget_heads/*", r"$") if not p.endswith(("_olmo", "_qwen3"))},
    "rater–item model": names("rater_item/*.json", r"\.json$"),
    "LoRA": {os.path.basename(p) for d in ("lora_budget_v2", "lora") for p in glob.glob(f"{R}/{d}/*") if os.path.isdir(p)},
}
panels = sorted(p for p in set().union(*COLS.values()) if "smoke" not in p)
lines = ["# Panel inventory (generated by panel_inventory.py)", "", "| panel | K | items | rating columns | " + " | ".join(COLS) + " |", "|---|---|---|---|" + "---|" * len(COLS)]
for p in panels:
    try: P = data_panels.load(p); K, (n, m) = P["K"], P["H"].shape
    except Exception as e: K, n, m = "?", "?", "?"
    lines.append(f"| {p} | {K} | {n} | {m} | " + " | ".join("✓" if p in v else "" for v in COLS.values()) + " |")
txt = "\n".join(lines) + "\n"; open(f"{R}/panel_inventory.md", "w").write(txt); print(txt)
